import assert from 'node:assert/strict';
import fs from 'node:fs';import vm from 'node:vm';import ts from 'typescript';
const module={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/plan-contracts.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{module,exports:module.exports});
const {INCLUDED_PLANS,includedPlanName,summarizePlans,filterPlanSummaries}=module.exports;
assert.equal(INCLUDED_PLANS.length,35);
for(const p of INCLUDED_PLANS)assert.equal(includedPlanName(p),p);
assert.equal(includedPlanName(' ★ペア　デイＳ会員 '),'★ペア デイS会員');
for(const p of ['休会','デイ会員（対象外）','新プラン',null,''])assert.equal(includedPlanName(p),null);
const row={year:2026,month:9,storeName:'巣鴨',planSubscribers:20,suspensions:2};
const members=[{...row,planName:'デイ会員',isActive:1},{...row,planName:'対象外',isActive:1},{...row,planName:'デイ会員',isActive:0}];
assert.equal(summarizePlans(members).reduce((n,p)=>n+p.count,0),1);
const result=filterPlanSummaries([row,{...row,month:8},{...row,storeName:'船橋'}],members);
assert.equal(result[0].planSubscribers,1);assert.equal(result[0].activePlanSubscribers,1);assert.equal(result[0].suspensions,2);
assert.equal(result[1].planSubscribers,20);assert.equal(result[1].planFilterApplied,false);assert.equal(result[1].activePlanSubscribers,18);
assert.equal(result[2].planFilterApplied,false);
assert.equal(filterPlanSummaries([row],[{...row,planName:'対象外',isActive:1}])[0].planSubscribers,0);
assert.equal(row.planSubscribers,20);
console.log('PASS: 35 plans, variants, exclusions, inactive members, zero matches, historical/store isolation, no double suspension subtraction');
